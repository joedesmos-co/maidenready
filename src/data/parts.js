/*
 * Part image catalog checklist (developer-facing):
 * - Do not scrape random store images for public use.
 * - Prefer own photos, manufacturer-approved images, or properly licensed images.
 * - Keep SVG placeholders when image rights are unclear.
 * - Local assets live under public/parts/... and are referenced via imagePath.
 * - Optional metadata: imageCredit, imageSourceUrl, imageLicense, imageNeedsReview.
 */
const normalizeCommonFields = (part, categoryKey) => {
  const presetImageFields = applyPresetPartImageFields(part.id, categoryKey);

  return {
    ...part,
    category: categoryKey,
    type: part.type ?? categoryType[categoryKey] ?? categoryKey,
    compatibleClasses: getCompatibleClasses(part),
    imagePath: firstValue(presetImageFields?.imagePath, part.imagePath),
    imageCredit: firstValue(
      part.imageCredit,
      part.image_credit,
      presetImageFields?.imageCredit,
    ),
    imageSourceUrl: firstValue(
      part.imageSourceUrl,
      part.image_source_url,
      presetImageFields?.imageSourceUrl,
    ),
    imageLicense: firstValue(
      part.imageLicense,
      part.image_license,
      presetImageFields?.imageLicense,
    ),
    imageNeedsReview: presetImageFields
      ? firstValue(
          part.imageNeedsReview,
          part.image_needs_review,
          presetImageFields.imageNeedsReview,
        )
      : Boolean(firstValue(part.imageNeedsReview, part.image_needs_review, false)),
    keySpecs: part.keySpecs ?? [],
    price_usd: firstValue(part.price_usd, part.price),
    weight_g: firstValue(part.weight_g, part.weightG),
    price: firstValue(part.price, part.price_usd),
    weightG: firstValue(part.weightG, part.weight_g),
  };
};

const normalizeCategoryFields = (part, categoryKey) => {
  switch (categoryKey) {
    case "frame": {
      const stackMounts = firstValue(part.stack_mounts, part.stackMounts, []);
      const motorMount = firstValue(part.motor_mount, part.motorMounts, []);

      return {
        ...part,
        size: firstValue(part.size, "5-inch"),
        max_prop_in: firstValue(part.max_prop_in, part.maxPropInches),
        stack_mounts: stackMounts,
        motor_mount: motorMount,
        maxPropInches: firstValue(part.maxPropInches, part.max_prop_in),
        stackMounts,
        motorMounts: Array.isArray(motorMount) ? motorMount : [motorMount],
      };
    }

    case "motors":
      return {
        ...part,
        recommended_cells: firstValue(
          part.recommended_cells,
          part.recommendedCells,
          [],
        ),
        max_current_a: firstValue(part.max_current_a, part.maxCurrentA),
        estimated_thrust_g: firstValue(part.estimated_thrust_g, part.thrustG),
        motor_mount: firstValue(part.motor_mount, part.mountPattern),
        recommendedCells: firstValue(
          part.recommendedCells,
          part.recommended_cells,
          [],
        ),
        maxCurrentA: firstValue(part.maxCurrentA, part.max_current_a),
        thrustG: firstValue(part.thrustG, part.estimated_thrust_g),
        mountPattern: firstValue(part.mountPattern, part.motor_mount),
      };

    case "esc":
      return {
        ...part,
        amp_rating: firstValue(part.amp_rating, part.continuousAmp),
        burst_amp_rating: firstValue(part.burst_amp_rating, part.burstAmp),
        stack_mount: firstValue(part.stack_mount, part.mountPattern),
        supported_cells: firstValue(part.supported_cells, part.supportedCells, []),
        continuousAmp: firstValue(part.continuousAmp, part.amp_rating),
        burstAmp: firstValue(part.burstAmp, part.burst_amp_rating),
        mountPattern: firstValue(part.mountPattern, part.stack_mount),
        supportedCells: firstValue(part.supportedCells, part.supported_cells, []),
      };

    case "flightController":
      return {
        ...part,
        stack_mount: firstValue(part.stack_mount, part.mountPattern),
        mountPattern: firstValue(part.mountPattern, part.stack_mount),
      };

    case "props":
      return {
        ...part,
        size_in: firstValue(part.size_in, part.diameterInches),
        diameterInches: firstValue(part.diameterInches, part.size_in),
      };

    case "battery":
      return {
        ...part,
        capacity_mah: firstValue(part.capacity_mah, part.capacityMah),
        c_rating: firstValue(part.c_rating, part.cRating),
        capacityMah: firstValue(part.capacityMah, part.capacity_mah),
        cRating: firstValue(part.cRating, part.c_rating),
      };

    case "camera":
    case "vtx":
      return {
        ...part,
        video_system: firstValue(part.video_system, part.videoSystem),
        digital_system: firstValue(part.digital_system, part.digitalSystem),
        videoSystem: firstValue(part.videoSystem, part.video_system),
        digitalSystem: firstValue(part.digitalSystem, part.digital_system),
      };

    default:
      return part;
  }
};

const normalizePart = (part, categoryKey) =>
  normalizeCategoryFields(normalizeCommonFields(part, categoryKey), categoryKey);

const withPartGuidance = (catalog) =>
  Object.fromEntries(
    Object.entries(catalog).map(([categoryKey, categoryParts]) => [
      categoryKey,
      categoryParts.map((part) =>
        normalizePart(
          {
            ...part,
            bestFor:
              part.bestFor ??
              partGuidance[part.id]?.bestFor ??
              categoryGuidance[categoryKey]?.bestFor,
            watchOutFor:
              part.watchOutFor ??
              partGuidance[part.id]?.watchOutFor ??
              categoryGuidance[categoryKey]?.watchOutFor,
          },
          categoryKey,
        ),
      ),
    ]),
  );

